"""Phase 10 增量 1:抽出「值不值得加」之前,決策規則對一批輸入的結果([S700])。

輸入由 `cases()` 依固定順序造出來:評分格用到的欄位(狀態、曝光、點擊、轉換、營收)各取正數、零、
負數、缺值、布林,配速與預算取邊界,另加既有決策測試的輸入形狀(現況只有預算、缺現況、缺指標、
沒有證據、證據過期與剛好 15 分鐘、沒有任務)。`EXPECTED` 是凍結舊規則(`frozen_policy_e8b26f6`,
即 main e8b26f6 的決策規則原樣)對每一筆輸入的結果摘要,改 `cases()` 就要用凍結舊規則重產。
摘要是結果全部欄位的標準寫法取雜湊前 12 碼,加一個字母標結果種類,失敗時看得出是哪一種變了。
"""

import hashlib
